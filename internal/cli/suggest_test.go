func TestWriteDraftFileWritesOnceAndLeavesNoTemporaryFile(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "tagrules.yaml")
	draft := []byte("# generated by tag-refactor devel\nversion: 1\nkeys: {}\n")

	if err := writeDraftFile(path, draft); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != string(draft) {
		t.Fatalf("draft = %q, err = %v", got, err)
	}

	err = writeDraftFile(path, []byte("other"))
	if e, ok := errkind.As(err); !ok || e.Kind != errkind.InvalidInput || !strings.Contains(e.Detail, "already exists") {
		t.Fatalf("err = %v", err)
	}
	if got, _ := os.ReadFile(path); string(got) != string(draft) {
		t.Fatal("the existing file was overwritten")
	}
	entries, err := os.ReadDir(dir)
	if err != nil || len(entries) != 1 {
		t.Fatalf("entries = %v, err = %v", entries, err)
	}

	err = writeDraftFile(filepath.Join(dir, "missing", "tagrules.yaml"), draft)
	if e, ok := errkind.As(err); !ok || e.Kind != errkind.StorageFailed || e.Hint == "" {
		t.Fatalf("err = %v", err)
	}
}

func TestWriteDraftFileWithoutHardLinks(t *testing.T) {
	draft := []byte("version: 1\nkeys: {}\n")
	noLink := func(string, string) error { return &os.LinkError{Op: "link", Err: errors.ErrUnsupported} }

	t.Run("renames when the name is free", func(t *testing.T) {
		dir := t.TempDir()
		path := filepath.Join(dir, "tagrules.yaml")
		if err := writeDraftFileWith(path, draft, noLink, os.Rename); err != nil {
			t.Fatal(err)
		}
		if got, err := os.ReadFile(path); err != nil || string(got) != string(draft) {
			t.Fatalf("draft = %q, err = %v", got, err)
		}
		if entries, _ := os.ReadDir(dir); len(entries) != 1 {
			t.Fatalf("entries = %v", entries)
		}
	})

	t.Run("refuses an existing file", func(t *testing.T) {
		dir := t.TempDir()
		path := filepath.Join(dir, "tagrules.yaml")
		if err := os.WriteFile(path, []byte("mine"), 0o600); err != nil {
			t.Fatal(err)
		}
		err := writeDraftFileWith(path, draft, noLink, os.Rename)
		if e, ok := errkind.As(err); !ok || e.Kind != errkind.InvalidInput || !strings.Contains(e.Detail, "already exists") {
			t.Fatalf("err = %v", err)
		}
		if got, _ := os.ReadFile(path); string(got) != "mine" {
			t.Fatal("the existing file was overwritten")
		}
		if entries, _ := os.ReadDir(dir); len(entries) != 1 {
			t.Fatalf("entries = %v", entries)
		}
	})

	t.Run("leaves nothing when the name cannot be given", func(t *testing.T) {
		dir := t.TempDir()
		path := filepath.Join(dir, "tagrules.yaml")
		failed := func(string, string) error { return &os.LinkError{Op: "rename", Err: fs.ErrPermission} }
		err := writeDraftFileWith(path, draft, noLink, failed)
		if e, ok := errkind.As(err); !ok || e.Kind != errkind.StorageFailed {
			t.Fatalf("err = %v", err)
		}
		if entries, _ := os.ReadDir(dir); len(entries) != 0 {
			t.Fatalf("entries = %v, want an empty folder", entries)
		}
	})
}

func TestCheckOutputPath(t *testing.T) {
	dir := t.TempDir()
	existing := filepath.Join(dir, "exists.yaml")
	if err := os.WriteFile(existing, nil, 0o600); err != nil {
		t.Fatal(err)
	}
	cases := []struct {
		path   string
		detail string
	}{
		{filepath.Join(dir, "new.yaml"), ""},
		{existing, "already exists"},
		{filepath.Join(dir, "missing", "new.yaml"), "does not exist"},
		{filepath.Join(existing, "new.yaml"), "does not exist"},
	}
	for _, tc := range cases {
		err := checkOutputPath(tc.path)
		if tc.detail == "" {
			if err != nil {
				t.Errorf("%s: %v", tc.path, err)
			}
			continue
		}
		if e, ok := errkind.As(err); !ok || e.Kind != errkind.InvalidInput || !strings.Contains(e.Detail, tc.detail) || e.Hint == "" {
			t.Errorf("%s: err = %v, want %q", tc.path, err, tc.detail)
		}
	}
}

func TestSuggestExitCodes(t *testing.T) {
	cases := []struct {
		o       outcome
		code    int
		meaning string
	}{
		{outcome{command: suggestCommandName}, ExitOK, "draft ready"},
		{outcome{command: suggestCommandName, needsReview: true}, ExitOK, "draft ready"},
		{outcome{command: suggestCommandName, regionsMissing: true, draftTooLarge: true}, ExitError, "results incomplete"},
		{outcome{command: suggestCommandName, draftTooLarge: true}, ExitError, "draft larger than 64 KiB"},
	}
	for _, tc := range cases {
		if code, meaning := tc.o.exitCode(); code != tc.code || meaning != tc.meaning {
			t.Errorf("%+v: got %d %q, want %d %q", tc.o, code, meaning, tc.code, tc.meaning)
		}
	}
}

// The rules package keeps its own copy of the region name form; it must
// agree with the one --region uses.
func TestRegionNameFormsAgree(t *testing.T) {
	for _, name := range []string{"us-east-1", "ap-northeast-1", "us-gov-west-1", "cn-north-1", "il-central-1",
		"useast1", "US-EAST-1", "us-east", "us-east-1 ", "-east-1", "a-b-1", "abcde-west-1", ""} {
		if rules.IsRegionName(name) != awsaccess.IsRegionName(name) {
			t.Errorf("%q: rules says %v, awsaccess says %v", name, rules.IsRegionName(name), awsaccess.IsRegionName(name))
		}
	}
}

