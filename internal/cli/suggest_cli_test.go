// BR6.7: Given keys that alone make the draft larger than 64 KiB, When rules
// suggest runs, Then the draft is printed, a warning says it cannot be read
// as it is, and the exit code is 1.
func TestSuggestDraftOver64KiBExitsOne(t *testing.T) {
	w := newWorld(t)
	tags := map[string]string{}
	for i := 0; i < 2000; i++ {
		tags[fmt.Sprintf("key-%04d-%s", i, strings.Repeat("x", 30))] = "v"
	}
	w.givenResources(testutil.TaggedResource{ARN: arnQA, Tags: tags})

	r := w.run("rules", "suggest", "--region", "us-east-1")

	r.requireExit(t, 1)
	if len(r.stdout) <= 64<<10 || !strings.HasPrefix(r.stdout, "# generated by tag-refactor ") {
		t.Fatalf("the draft must still be printed (%d bytes)", len(r.stdout))
	}
	requireContains(t, "stderr", r.stderr,
		"warning: the draft is larger than 64 KiB and cannot be read as it is; remove keys you do not need")
	requireContains(t, "stderr", r.stderr, "Exit code: 1 (draft larger than 64 KiB)")
}

// W2.3: Given no credentials, When rules suggest runs, Then the two-line
// error is shown and no draft is printed.
func TestSuggestWithoutCredentialsPrintsNoDraft(t *testing.T) {
	w := newWorld(t)
	w.env.WriteCredentials("")
	w.env.WriteConfig("[default]\nregion = us-east-1\n")

	r := w.run("rules", "suggest")

	r.requireExit(t, 1)
	requireTwoLineError(t, r)
	requireContains(t, "stderr", r.stderr, "no AWS credentials were found")
}

