// NFR5.9 with BR6.6: Given one region denies reading, When rules suggest
// runs, Then the draft is still printed with the incomplete region named in
// its first comments, standard error says the results are incomplete, and
// the exit code is 1.
func TestAcceptanceU3_NFR5_9_ADeniedRegionGivesAnIncompleteDraft(t *testing.T) {
	w := newWorld(t)
	denied := testutil.JSONError(http.StatusBadRequest, "AccessDeniedException", "not authorized to perform: tag:GetResources")
	w.fake.Handle("tag:GetResources", testutil.PerRegion(map[string]testutil.Handler{
		"eu-west-1": testutil.Static(denied),
		"us-east-1": testutil.TagPages([]testutil.TaggedResource{{ARN: arnQA, Tags: map[string]string{"env": "dev"}}}),
	}, testutil.TagPages(nil)))

	r := w.run("rules", "suggest")

	r.requireExit(t, 1)
	if !strings.HasPrefix(r.stdout, "# generated by tag-refactor ") {
		t.Fatalf("the draft must still be printed:\n%s", r.stdout)
	}
	requireMatch(t, "stdout", r.stdout, `(?m)^# account 123456789012, 2 of 3 regions, `)
	requireMatch(t, "stdout", r.stdout, `(?m)^# Results are incomplete: eu-west-1$`)
	requireContains(t, "stdout", r.stdout, "  \"env\": {}\n")
	requireContains(t, "stderr", r.stderr, "Results are incomplete")
	requireMatch(t, "stderr", r.stderr, `(?m)eu-west-1: AccessDenied \(tag:GetResources\)`)
	requireContains(t, "stderr", r.stderr, "Checked: tagged resources in 2 of 3 regions (tagging API)")
	requireContains(t, "stderr", r.stderr, "Exit code: 1 (results incomplete)")
	requireNotContains(t, "stderr", r.stderr, "Error:")
}

