// AC2.1.1 with security design §3: Given --output, When rules suggest runs,
// Then the draft is written to the file in UTF-8 (Japanese and characters
// outside the basic plane included), nothing is printed to standard output,
// and an existing file is never overwritten.
func TestAcceptanceU3_AC2_1_1_OutputWritesUTF8AndNeverOverwrites(t *testing.T) {
	w := newWorld(t)
	w.givenResources(
		testutil.TaggedResource{ARN: arnQA, Tags: map[string]string{"環境": "本番", "Owner": "チーム😀"}},
		testutil.TaggedResource{ARN: arnQB, Tags: map[string]string{"環境": "検証"}},
	)
	out := w.outputPath("tagrules.yaml")

	r := w.run("rules", "suggest", "--region", "us-east-1", "--output", out)

	r.requireExit(t, 0)
	if r.stdout != "" {
		t.Fatalf("stdout must be empty with --output, got:\n%s", r.stdout)
	}
	requireContains(t, "stderr", r.stderr, filepath.Base(out))
	draft := readDraft(t, out)
	if !utf8.ValidString(draft) || strings.HasPrefix(draft, "\xef\xbb\xbf") || strings.Contains(draft, "\r") {
		t.Fatalf("the draft must be UTF-8 without a BOM and with LF newlines: %q", draft)
	}
	if !strings.HasPrefix(draft, "# generated by tag-refactor ") {
		t.Fatalf("draft = %q", draft)
	}
	doc := decodeDraft(t, draft)
	if _, ok := doc.Keys["環境"]; !ok {
		t.Fatalf("the Japanese key is missing from the draft:\n%s", draft)
	}
	if _, ok := doc.Keys["Owner"]; !ok {
		t.Fatalf("Owner is missing from the draft:\n%s", draft)
	}
	scan := w.run("scan", "--region", "us-east-1", "--rules", out)
	requireNotContains(t, "scan stderr", scan.stderr, "Error:")

	calls := len(w.fake.Calls())
	again := w.run("rules", "suggest", "--region", "us-east-1", "--output", out)

	again.requireExit(t, 1)
	requireTwoLineError(t, again)
	requireContains(t, "stderr", again.stderr, "already exists")
	if readDraft(t, out) != draft {
		t.Fatal("the existing file was overwritten")
	}
	if n := len(w.fake.Calls()); n != calls {
		t.Fatalf("AWS was called %d times before the existing file was reported", n-calls)
	}
	entries, err := os.ReadDir(filepath.Dir(out))
	if err != nil || len(entries) != 1 {
		t.Fatalf("the folder must hold the draft only (no temporary file): %v %v", entries, err)
	}
}

// AC2.1.2: Given the draft of rules suggest makes Env and environment aliases
// of env, When plan runs with it, Then they are treated as key renames to env.
func TestAcceptanceU3_AC2_1_2_DraftAliasesBecomeKeyRenames(t *testing.T) {
	w := newWorld(t)
	w.givenResources(variantResources()...)
	w.givenAttachedPolicies(map[string]string{})
	suggest := w.run("rules", "suggest", "--region", "us-east-1")
	suggest.requireExit(t, 0)
	draft := w.givenRuleFile(suggest.stdout)

	r := w.run("plan", "--rules", draft, "--region", "us-east-1")

	r.requireExit(t, 2)
	requireMatch(t, "stdout", r.stdout, `(?m)^  ~ rename key\s+Env -> env\s+2 resources$`)
	requireMatch(t, "stdout", r.stdout, `(?m)^  ~ rename key\s+environment -> env\s+1 resource$`)
	requireContains(t, "stdout", r.stdout, "Summary: 3 to change")
	requireContains(t, "stderr", r.stderr, "values / required / remove are read but not applied to the plan yet")
}

// AC2.1.5: Given a rule file with a mistake, When plan runs, Then the line,
// the key and how to fix it are shown, the exit code is 1, and AWS is never
// called (NFR3.7). scan stops the same way.
func TestAcceptanceU3_AC2_1_5_RuleFileMistakesShowLineKeyAndFix(t *testing.T) {
	cases := []struct {
		name    string
		content string
		what    string
		fix     string
	}{
		{
			name:    "misspelled key",
			content: "version: 1\nkeys:\n  Environment:\n    aliases: [env]\nrequried:\n  Owner:\n    default: platform\n",
			what:    `line 5: unknown key "requried"`,
			fix:     `did you mean "required"?`,
		},
		{
			name:    "aliases not a list",
			content: "version: 1\nkeys:\n  Environment:\n    aliases: env\n",
			what:    `line 4: "aliases" must be a list`,
			fix:     `"- item" per line`,
		},
		{
			name:    "alias under two keys",
			content: "version: 1\nkeys:\n  Environment:\n    aliases: [env]\n  Stage:\n    aliases: [env]\n",
			what:    `line 6: the alias "env" is listed under "Environment" (line 4) and "Stage" (line 6)`,
			fix:     "keep the alias under one canonical key only",
		},
		{
			name: "CloudFormation resource type",
			content: "version: 1\nrequired:\n  Owner:\n    default: platform\n    when:\n" +
				"      - match: {resourceType: AWS::EC2::Instance}\n        value: infra\n",
			what: `line 6: write the resource type as scan shows it`,
			fix:  `write "ec2:instance"`,
		},
		{
			name:    "empty match",
			content: "version: 1\nrequired:\n  Owner:\n    when:\n      - match: {}\n        value: infra\n",
			what:    `line 5: a condition needs at least one of resourceType, region or tags`,
			fix:     `use "default" for a value that applies to every resource`,
		},
		{
			name:    "alias in a condition",
			content: "version: 1\nkeys:\n  Environment:\n    aliases: [env]\nrequired:\n  Owner:\n    when:\n      - match: {tags: {env: prod}}\n        value: infra\n",
			what:    `line 8: "env" is an alias of "Environment"; conditions compare tags after aliases are renamed`,
			fix:     `write "Environment" here`,
		},
		{
			name:    "removed alias",
			content: "version: 1\nkeys:\n  Environment:\n    aliases: [env]\nremove: [env]\n",
			what:    `line 5: "env" is an alias of "Environment"`,
			fix:     `the alias is renamed by the plan; remove it from "remove"`,
		},
		{
			name:    "unsupported version",
			content: "version: 2\nkeys: {}\n",
			what:    `line 1: rule file version 2 is not supported`,
			fix:     "this version of tag-refactor reads rule file version 1",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			w := newWorld(t)
			w.givenResources(testutil.TaggedResource{ARN: arnQA, Tags: map[string]string{"env": "prod"}})
			path := w.givenRuleFile(tc.content)

			plan := w.run("plan", "--rules", path, "--region", "us-east-1")
			scan := w.run("scan", "--rules", path, "--region", "us-east-1")

			for _, r := range []result{plan, scan} {
				r.requireExit(t, 1)
				requireTwoLineError(t, r)
				requireMatch(t, "stderr", r.stderr, `(?m)^Error: .*tagrules\.yaml `+regexp.QuoteMeta(tc.what)+`$`)
				requireMatch(t, "stderr", r.stderr, `(?m)^  Fix: .*`+regexp.QuoteMeta(tc.fix))
			}
			if calls := w.fake.Calls(); len(calls) != 0 {
				t.Fatalf("AWS was called with a broken rule file: %d calls (first %s)", len(calls), calls[0].Op)
			}
		})
	}
}

// NFR8.14: Given a rule file whose mistake is in a key with control and
// bidirectional characters, When plan runs, Then those characters are not
// printed as they are.
func TestAcceptanceU3_NFR8_14_RuleFileStringsAreSanitizedInMessages(t *testing.T) {
	w := newWorld(t)
	path := w.givenRuleFile("version: 1\n\"evil\\e[2J\\u202Ekey\": {}\nremove: [\"tmp\\e]0;x\\a\", \"aws:\\u202E\"]\n")

	r := w.run("plan", "--rules", path, "--region", "us-east-1")

	r.requireExit(t, 1)
	requireTwoLineError(t, r)
	requireContains(t, "stderr", r.stderr, "unknown key")
	for _, raw := range []string{"\x1b", "‮", "\a"} {
		requireNotContains(t, "stderr", r.stderr, raw)
	}
}

// NFR8.12: Given tag keys and values with control characters, bidirectional
// overrides, tag characters outside the basic plane and newlines, When rules
// suggest runs, Then none of them is printed as it is, and the draft reads
// back to the original strings.
func TestAcceptanceU3_NFR8_12_DraftEscapesUnprintableCharacters(t *testing.T) {
	key := "team\u009b31m‮\U000E0001\U000E0041"
	second := "Team\x1b[2J\nx"
	value := "a \"b\\c\x1b"
	spelling := "A \"b\\c\x1b"
	w := newWorld(t)
	w.givenResources(
		testutil.TaggedResource{ARN: arnQA, Tags: map[string]string{key: value}},
		testutil.TaggedResource{ARN: arnQB, Tags: map[string]string{key: spelling}},
		testutil.TaggedResource{ARN: arnQC, Tags: map[string]string{key: value}},
		testutil.TaggedResource{ARN: arnB1, Tags: map[string]string{second: "v"}},
	)

	r := w.run("rules", "suggest", "--region", "us-east-1")

	r.requireExit(t, 0)
	for _, raw := range []string{"\u009b", "‮", "\U000E0001", "\U000E0041", "\x1b", " "} {
		requireNotContains(t, "stdout", r.stdout, raw)
	}
	doc := decodeDraft(t, r.stdout)
	rule, ok := doc.Keys[key]
	if !ok {
		var got []string
		for k := range doc.Keys {
			got = append(got, k)
		}
		t.Fatalf("the key did not read back: got %q", got)
	}
	if got := rule.Values[value]; !slices.Equal(got, []string{spelling}) {
		t.Fatalf("the value candidates did not read back: %q", rule.Values)
	}
	if _, ok := doc.Keys[second]; !ok {
		t.Fatalf("the second key did not read back:\n%s", r.stdout)
	}
	scan := w.run("scan", "--region", "us-east-1", "--rules", w.givenRuleFile(r.stdout))
	requireNotContains(t, "scan stderr", scan.stderr, "Error:")
}

