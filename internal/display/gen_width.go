//go:build ignore

// gen_width writes width_table.go: the ranges of the characters whose East
// Asian Width is W (wide) or F (fullwidth), which take two columns on a
// terminal (U4 NFR design, Q3). It reads EastAsianWidth.txt of the Unicode
// version of the Go that runs it (unicode.Version), so the table and the
// unicode package always agree; the version is written to the table as
// widthTableUnicodeVersion, and a test fails when a newer Go has a newer
// Unicode version than the table (cicd-pipeline.md).
//
// Run it from internal/display with "go generate" (or "go run gen_width.go").
// It downloads the file; -in reads a copy of it instead. The URL and the
// SHA-256 of the file are written to the head of the table, so the same
// version can be checked to give the same table. It is not built, tested or
// measured: the build tag ignore leaves it out.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
	"time"
	"unicode"
)

func main() {
	in := flag.String("in", "", "read EastAsianWidth.txt from this file instead of downloading it")
	out := flag.String("out", "width_table.go", "the Go file to write")
	flag.Parse()

	url := "https://www.unicode.org/Public/" + unicode.Version + "/ucd/EastAsianWidth.txt"
	data, err := read(url, *in)
	if err != nil {
		log.Fatal(err)
	}
	if !bytes.Contains(data[:min(len(data), 200)], []byte("EastAsianWidth-"+unicode.Version+".txt")) {
		log.Fatalf("the file is not EastAsianWidth-%s.txt", unicode.Version)
	}
	ranges, err := wideRanges(data)
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(data)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_width.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Source: %s\n// SHA-256: %s\n\n", url, hex.EncodeToString(sum[:]))
	fmt.Fprintf(&b, "package display\n\n")
	fmt.Fprintf(&b, "// widthTableUnicodeVersion is the Unicode version of wideRanges.\n")
	fmt.Fprintf(&b, "const widthTableUnicodeVersion = %q\n\n", unicode.Version)
	fmt.Fprintf(&b, "// wideRanges are the characters of East Asian Width W and F, sorted.\n")
	fmt.Fprintf(&b, "var wideRanges = []runeRange{\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r[0], r[1])
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(url, path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 16<<20))
}

// wideRanges reads lines such as "1100..115F;W # ..." and "3000;F # ...",
// keeps W and F, and joins adjacent ranges.
func wideRanges(data []byte) ([][2]rune, error) {
	var out [][2]rune
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		cps, prop, ok := strings.Cut(line, ";")
		if !ok {
			continue
		}
		prop = strings.TrimSpace(prop)
		if prop != "W" && prop != "F" {
			continue
		}
		lo, hi, isRange := strings.Cut(strings.TrimSpace(cps), "..")
		if !isRange {
			hi = lo
		}
		l, err := strconv.ParseUint(lo, 16, 32)
		if err != nil {
			return nil, err
		}
		h, err := strconv.ParseUint(hi, 16, 32)
		if err != nil {
			return nil, err
		}
		if n := len(out); n > 0 && out[n-1][1]+1 == rune(l) {
			out[n-1][1] = rune(h)
			continue
		}
		out = append(out, [2]rune{rune(l), rune(h)})
	}
	return out, sc.Err()
}
