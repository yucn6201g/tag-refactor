// Unit tests of the output of rules suggest (U3), written after the
// implementation.

func TestWriteDraftWritesTheBytesAsTheyAreToStandardOutput(t *testing.T) {
	p, out, errOut := newPrinter()
	draft := "# generated by tag-refactor devel\nversion: 1\nkeys:\n  \"a\\u001B\": {}\n"

	p.WriteDraft([]byte(draft))

	if out.String() != draft || errOut.Len() != 0 {
		t.Fatalf("stdout = %q, stderr = %q", out.String(), errOut.String())
	}
	broken := New(failingWriter{}, failingWriter{})
	broken.WriteDraft([]byte(draft))
	if broken.WriteErr() == nil {
		t.Fatal("a failed write must be kept")
	}
}

func TestTheMessagesOfRulesSuggestGoToStandardError(t *testing.T) {
	p, out, errOut := newPrinter()
	snap := &inventory.Snapshot{
		EnabledRegions: []string{"eu-west-1", "us-east-1", "us-west-2"},
		ScannedRegions: []string{"eu-west-1", "us-east-1"},
		FailedRegions:  []inventory.FailedRegion{{Region: "eu-west-1", Kind: "AccessDenied", Operation: "tag:GetResources"}},
	}

	p.DraftIncomplete(nil)
	p.DraftIncomplete(snap.FailedRegions)
	p.DraftWritten("dir/tag\x1brules.yaml", 1)
	p.DraftWritten("tagrules.yaml", 12)
	p.SuggestScope(snap)

	want := "! Results are incomplete\n" +
		"    eu-west-1: AccessDenied (tag:GetResources)\n" +
		"Draft written to dir/tag\\u{1B}rules.yaml (1 key)\n" +
		"Draft written to tagrules.yaml (12 keys)\n" +
		"Checked: tagged resources in 1 of 3 regions (tagging API)\n"
	if errOut.String() != want {
		t.Fatalf("stderr:\n%s\nwant:\n%s", errOut.String(), want)
	}
	if out.Len() != 0 || strings.Contains(errOut.String(), "\x1b") {
		t.Fatalf("stdout = %q", out.String())
	}
}
